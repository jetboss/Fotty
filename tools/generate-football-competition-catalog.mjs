#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = resolve(root, "shared/reference-data/football-competitions-2026-27.json");
const swiftPath = resolve(root, "Fotty/Core/Data/FootballCompetitionCatalog.generated.swift");
const typescriptPath = resolve(root, "web/src/lib/football-competition-catalog.generated.ts");
const checkOnly = process.argv.includes("--check");
const source = JSON.parse(await readFile(inputPath, "utf8"));

function assertManifest() {
  if (source.schemaVersion !== 1 || !source.season || !source.verifiedAt || !source.validThrough) {
    throw new Error("Football competition manifest metadata is incomplete.");
  }
  const validThrough = Date.parse(source.validThrough);
  if (!Number.isFinite(validThrough)) throw new Error("Football competition validThrough is not an ISO-8601 date.");
  if (checkOnly && Date.now() > validThrough) {
    throw new Error(`Football competition catalog expired on ${source.validThrough}; verify the new season before release.`);
  }
  const ids = new Set();
  if (!Array.isArray(source.additionalClubIdentities)) {
    throw new Error("additionalClubIdentities must be an array.");
  }
  const additionalAliases = new Map();
  for (const club of source.additionalClubIdentities) {
    for (const value of [club.name, ...club.aliases]) {
      const key = normalizedManifestKey(value);
      const owner = additionalAliases.get(key);
      if (owner && owner !== club.name) {
        throw new Error(`Additional club alias collision: ${value} maps to both ${owner} and ${club.name}`);
      }
      additionalAliases.set(key, club.name);
    }
  }
  for (const competition of source.competitions) {
    if (ids.has(competition.id)) throw new Error(`Duplicate competition id: ${competition.id}`);
    ids.add(competition.id);
    if (!Array.isArray(competition.providerAliases)) {
      throw new Error(`${competition.id} providerAliases must be an array.`);
    }
    if (competition.clubs.length !== competition.expectedClubCount) {
      throw new Error(`${competition.id} expected ${competition.expectedClubCount} clubs, found ${competition.clubs.length}`);
    }
    const names = competition.clubs.map((club) => club.name.toLocaleLowerCase("en"));
    if (new Set(names).size !== names.length) throw new Error(`Duplicate club in ${competition.id}`);
    const aliases = new Map();
    for (const club of competition.clubs) {
      for (const value of [club.name, ...club.aliases]) {
        const key = normalizedManifestKey(value);
        const owner = aliases.get(key);
        if (owner && owner !== club.name) {
          throw new Error(`${competition.id} alias collision: ${value} maps to both ${owner} and ${club.name}`);
        }
        aliases.set(key, club.name);
      }
    }
  }
}

function normalizedManifestKey(value) {
  const ignored = new Set(["fc", "afc", "cf", "ac", "club", "sc", "sv", "rc", "rcd", "ud", "losc", "ogc", "estac", "stade", "olympique", "and"]);
  return value.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase()
    .split(/[^a-z0-9]+/).filter((token) => token && !ignored.has(token))
    .map((token) => token === "utd" ? "united" : token).join("");
}

function swiftString(value) {
  return `"${String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function swiftArray(values, indent) {
  if (values.length === 0) return "[]";
  return `[${values.map(swiftString).join(", ")}]`;
}

function renderSwift() {
  const ids = source.competitions.map((item) => `    case ${item.id}`).join("\n");
  const snapshots = source.competitions.map((competition) => {
    const clubs = competition.clubs.map((club) =>
      `                FootballCompetitionClub(name: ${swiftString(club.name)}, aliases: ${swiftArray(club.aliases)})`
    ).join(",\n");
    return `        .${competition.id}: FootballCompetitionSnapshot(\n` +
      `            id: .${competition.id},\n` +
      `            displayName: ${swiftString(competition.displayName)},\n` +
      `            providerName: ${swiftString(competition.providerName)},\n` +
      `            providerAliases: ${swiftArray(competition.providerAliases)},\n` +
      `            officialSource: URL(string: ${swiftString(competition.officialSource)})!,\n` +
      `            expectedClubCount: ${competition.expectedClubCount},\n` +
      `            clubs: [\n${clubs}\n            ]\n` +
      `        )`;
  }).join(",\n");
  const additionalClubs = source.additionalClubIdentities.map((club) =>
    `        FootballCompetitionClub(name: ${swiftString(club.name)}, aliases: ${swiftArray(club.aliases)})`
  ).join(",\n");

  return `// Generated by tools/generate-football-competition-catalog.mjs. Do not edit by hand.\n` +
`import Foundation\n\n` +
`enum FootballCompetitionID: String, CaseIterable, Codable, Sendable {\n${ids}\n}\n\n` +
`struct FootballCompetitionClub: Equatable, Sendable {\n    let name: String\n    let aliases: [String]\n}\n\n` +
`struct FootballCompetitionSnapshot: Equatable, Sendable {\n    let id: FootballCompetitionID\n    let displayName: String\n    let providerName: String\n    let providerAliases: [String]\n    let officialSource: URL\n    let expectedClubCount: Int\n    let clubs: [FootballCompetitionClub]\n\n    var officialClubNames: [String] { clubs.map(\\.name) }\n    var searchAliases: [String] { clubs.flatMap { [$0.name] + $0.aliases } }\n}\n\n` +
`enum FootballCompetitionCatalog {\n` +
`    static let schemaVersion = ${source.schemaVersion}\n` +
`    static let seasonLabel = ${swiftString(source.season)}\n` +
`    static let verifiedAt = ISO8601DateFormatter().date(from: ${swiftString(source.verifiedAt + "T00:00:00Z")})!\n` +
`    static let validThrough = ISO8601DateFormatter().date(from: ${swiftString(source.validThrough)})!\n\n` +
`    static let additionalClubIdentities: [FootballCompetitionClub] = [\n${additionalClubs}\n    ]\n\n` +
`    static let snapshots: [FootballCompetitionID: FootballCompetitionSnapshot] = [\n${snapshots}\n    ]\n\n` +
`    static func snapshot(_ id: FootballCompetitionID) -> FootballCompetitionSnapshot {\n        snapshots[id]!\n    }\n\n` +
`    static func officialClubNames(for id: FootballCompetitionID) -> [String] {\n        snapshot(id).officialClubNames\n    }\n\n` +
`    static func searchAliases(for id: FootballCompetitionID) -> [String] {\n        snapshot(id).searchAliases\n    }\n\n` +
`    static func isFresh(at date: Date = Date()) -> Bool {\n        date <= validThrough\n    }\n\n` +
`    static func contains(_ rawName: String, in id: FootballCompetitionID) -> Bool {\n        officialName(for: rawName, in: id) != nil\n    }\n\n` +
`    static func containsBoth(home: String, away: String, in id: FootballCompetitionID) -> Bool {\n        contains(home, in: id) && contains(away, in: id)\n    }\n\n` +
`    /// One provider-independent senior-club identity shared by matching, filtering and fixtures.\n` +
`    static func canonicalClubID(for rawName: String) -> String? {\n` +
`        guard !isNonSeniorTeam(rawName) else { return nil }\n` +
`        let key = normalizedKey(rawName)\n` +
`        let allClubs = snapshots.values.flatMap(\\.clubs) + additionalClubIdentities\n` +
`        let matches = Set(allClubs.compactMap { club in\n` +
`                ([club.name] + club.aliases).contains { normalizedKey($0) == key }\n` +
`                    ? normalizedKey(club.name)\n` +
`                    : nil\n` +
`        })\n` +
`        return matches.count == 1 ? matches.first : nil\n` +
`    }\n\n` +
`    /// Known clubs collapse to their canonical identity; unknown teams retain a deterministic key.\n` +
`    static func canonicalTeamKey(_ rawName: String) -> String {\n` +
`        canonicalClubID(for: rawName) ?? normalizedKey(rawName)\n` +
`    }\n\n` +
`    static func officialName(for rawName: String, in id: FootballCompetitionID) -> String? {\n` +
`        guard !isNonSeniorTeam(rawName) else { return nil }\n` +
`        let key = normalizedKey(rawName)\n` +
`        return snapshot(id).clubs.first { club in\n` +
`            ([club.name] + club.aliases).contains { normalizedKey($0) == key }\n` +
`        }?.name\n` +
`    }\n\n` +
`    static func providerBootstrap() -> [String: [String]] {\n` +
`        Dictionary(uniqueKeysWithValues: snapshots.values.flatMap { snapshot in\n` +
`            ([snapshot.providerName] + snapshot.providerAliases).map { ($0, snapshot.officialClubNames) }\n` +
`        })\n` +
`    }\n\n` +
`    static func socialFallback() -> [String: [String]] {\n` +
`        Dictionary(uniqueKeysWithValues: snapshots.values.map { ($0.displayName, $0.officialClubNames) })\n` +
`    }\n\n` +
`    private static func isNonSeniorTeam(_ value: String) -> Bool {\n` +
`        let pattern = #"\\b(?:u(?:18|19|21|23)|under[ -]?(?:18|19|21|23)|women|ladies|youth|academy|reserves?)\\b"#\n` +
`        return value.lowercased().range(of: pattern, options: .regularExpression) != nil\n` +
`    }\n\n` +
`    private static func normalizedKey(_ value: String) -> String {\n` +
`        let folded = value.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "en_US_POSIX"))\n` +
`        let ignored: Set<String> = ["fc", "afc", "cf", "ac", "club", "sc", "sv", "rc", "rcd", "ud", "losc", "ogc", "estac", "stade", "olympique", "and"]\n` +
`        return folded.components(separatedBy: CharacterSet.alphanumerics.inverted)\n` +
`            .filter { !$0.isEmpty && !ignored.contains($0.lowercased()) }\n` +
`            .map { $0.lowercased() == "utd" ? "united" : $0.lowercased() }\n` +
`            .joined()\n` +
`    }\n` +
`}\n\n` +
`enum PremierLeagueClubCatalog {\n` +
`    static let seasonLabel = FootballCompetitionCatalog.seasonLabel\n` +
`    static let officialClubNames = FootballCompetitionCatalog.officialClubNames(for: .premierLeague)\n` +
`    static let searchAliases = FootballCompetitionCatalog.searchAliases(for: .premierLeague)\n` +
`    static func contains(_ rawName: String) -> Bool { FootballCompetitionCatalog.contains(rawName, in: .premierLeague) }\n` +
`    static func officialName(for rawName: String) -> String? { FootballCompetitionCatalog.officialName(for: rawName, in: .premierLeague) }\n` +
`    static func containsBoth(home: String, away: String) -> Bool { FootballCompetitionCatalog.containsBoth(home: home, away: away, in: .premierLeague) }\n` +
`}\n`;
}

function renderTypeScript() {
  const object = Object.fromEntries(source.competitions.map((competition) => [competition.id, {
    displayName: competition.displayName,
    providerName: competition.providerName,
    providerAliases: competition.providerAliases,
    officialSource: competition.officialSource,
    expectedClubCount: competition.expectedClubCount,
    clubs: competition.clubs,
  }]));
  return `// Generated by tools/generate-football-competition-catalog.mjs. Do not edit by hand.\n` +
`export const FOOTBALL_REFERENCE_SEASON = ${JSON.stringify(source.season)};\n` +
`export const FOOTBALL_REFERENCE_VERIFIED_AT = ${JSON.stringify(source.verifiedAt)};\n` +
`export const FOOTBALL_REFERENCE_VALID_THROUGH = ${JSON.stringify(source.validThrough)};\n\n` +
`export const FOOTBALL_COMPETITIONS = ${JSON.stringify(object, null, 2)} as const;\n\n` +
`export const ADDITIONAL_FOOTBALL_CLUB_IDENTITIES = ${JSON.stringify(source.additionalClubIdentities, null, 2)} as const;\n\n` +
`export type CurrentFootballCompetitionId = keyof typeof FOOTBALL_COMPETITIONS;\n\n` +
`function normalizedKey(value: string) {\n` +
`  const ignored = new Set(["fc", "afc", "cf", "ac", "club", "sc", "sv", "rc", "rcd", "ud", "losc", "ogc", "estac", "stade", "olympique", "and"]);\n` +
`  return value.normalize("NFD").replace(/\\p{Diacritic}/gu, "").toLowerCase().split(/[^a-z0-9]+/).filter((token) => token && !ignored.has(token)).map((token) => token === "utd" ? "united" : token).join("");\n` +
`}\n\n` +
`function isNonSeniorTeam(value: string) {\n` +
`  return /\\b(?:u(?:18|19|21|23)|under[ -]?(?:18|19|21|23)|women|ladies|youth|academy|reserves?)\\b/i.test(value);\n` +
`}\n\n` +
`export function currentCompetitionOfficialNames(id: CurrentFootballCompetitionId) {\n` +
`  return FOOTBALL_COMPETITIONS[id].clubs.map((club) => club.name);\n` +
`}\n\n` +
`export function isCurrentCompetitionClub(id: CurrentFootballCompetitionId, value: string) {\n` +
`  if (isNonSeniorTeam(value)) return false;\n` +
`  const key = normalizedKey(value);\n` +
`  return FOOTBALL_COMPETITIONS[id].clubs.some((club) => [club.name, ...club.aliases].some((name) => normalizedKey(name) === key));\n` +
`}\n\n` +
`export function isCurrentCompetitionPair(id: CurrentFootballCompetitionId, home: string, away: string) {\n` +
`  return isCurrentCompetitionClub(id, home) && isCurrentCompetitionClub(id, away);\n` +
`}\n\n` +
`export function canonicalFootballClubId(value: string) {\n` +
`  if (isNonSeniorTeam(value)) return undefined;\n` +
`  const key = normalizedKey(value);\n` +
`  const matches = new Set<string>();\n` +
`  const considerClub = (club: { readonly name: string; readonly aliases: readonly string[] }) => {\n` +
`      if ([club.name, ...club.aliases].some((name) => normalizedKey(name) === key)) {\n` +
`        matches.add(normalizedKey(club.name));\n` +
`      }\n` +
`  };\n` +
`  for (const competition of Object.values(FOOTBALL_COMPETITIONS)) {\n` +
`    for (const club of competition.clubs) considerClub(club);\n` +
`  }\n` +
`  for (const club of ADDITIONAL_FOOTBALL_CLUB_IDENTITIES) considerClub(club);\n` +
`  return matches.size === 1 ? matches.values().next().value : undefined;\n` +
`}\n\n` +
`export function canonicalFootballTeamKey(value: string) {\n` +
`  return canonicalFootballClubId(value) ?? normalizedKey(value);\n` +
`}\n\n` +
`export function isFootballReferenceFresh(at = new Date()) {\n` +
`  return at.getTime() <= Date.parse(FOOTBALL_REFERENCE_VALID_THROUGH);\n` +
`}\n`;
}

assertManifest();
const outputs = [[swiftPath, renderSwift()], [typescriptPath, renderTypeScript()]];
let mismatched = false;
for (const [path, expected] of outputs) {
  const actual = await readFile(path, "utf8").catch(() => "");
  if (actual !== expected) {
    mismatched = true;
    if (!checkOnly) await writeFile(path, expected);
  }
}
if (checkOnly && mismatched) {
  throw new Error("Generated football competition catalogs are out of date. Run tools/generate-football-competition-catalog.mjs.");
}
if (!checkOnly) console.log("Football competition catalogs generated from the shared 2026/27 manifest.");
